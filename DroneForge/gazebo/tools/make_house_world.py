#!/usr/bin/env python3
"""Builds worlds/droneforge_house.sdf from the AWS RoboMaker Small House world (third_party/small_house_src, ros2 branch, MIT No Attribution):
renames the world, sets a 4 ms physics step (the house costs about 3 ms of physics per 1 ms step on this laptop: 1 ms runs at 0.28x real time, 4 ms at 1.0x, and the drone flies fine at 4 ms) and adds the DroneForge 3-inch drone in the living room.
usage: python3 tools/make_house_world.py [x y yaw_rad] [--camera WIDTHxHEIGHT@FPS]
--camera writes models/droneforge_3in_house (a copy of the drone with that camera size and rate, and the camera level instead of tilted 15 deg down, as Nimbus mounts it; horizontal fov 1.668 rad = the Nimbus Air75 depth profile, fx 292.3 px at 640 px width) and puts that one in the world: the full 1280x720@30 stream renders at about 5 fps in this house
on the laptop's integrated graphics, and the navigation models work on 504x336 pictures anyway."""
import os, re, sys
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
args = [a for a in sys.argv[1:]]
cam = None
if "--camera" in args:
    i = args.index("--camera"); cam = args[i + 1]; del args[i:i + 2]
x, y, yaw = (float(v) for v in args[:3]) if len(args) >= 3 else (2.6, -3.2, -1.5708)
model = "droneforge_3in"
if cam:
    m = re.fullmatch(r"(\d+)x(\d+)@(\d+)", cam); assert m, "use WIDTHxHEIGHT@FPS"
    w, h, fps = m.groups()
    import shutil
    dst = os.path.join(HERE, "models/droneforge_3in_house"); shutil.rmtree(dst, ignore_errors=True); shutil.copytree(os.path.join(HERE, "models/droneforge_3in"), dst)
    p = os.path.join(dst, "model.sdf"); t = open(p).read()
    t = t.replace("<width>1280</width>", f"<width>{w}</width>").replace("<height>720</height>", f"<height>{h}</height>")
    i0 = t.index('<sensor name="dji_o4_camera"'); i1 = t.index("</sensor>", i0)
    r0 = t.find('<!-- MTF-02 TOF Rangefinder')                        # the house drone has no rendered rangefinder: the sim FC computes the range (a gpu_lidar costs the 30 fps camera ~2 fps)
    if r0 >= 0:
        r1 = t.index('</sensor>', r0) + len('</sensor>'); t = t[:r0] + '<!-- MTF-02 range: computed by the sim FC (controllers/fc_v4_5_bridge.py) -->' + t[r1:]
        i0 = t.index('<sensor name="dji_o4_camera"'); i1 = t.index("</sensor>", i0)
    t = t[:i0] + t[i0:i1].replace("<update_rate>30</update_rate>", f"<update_rate>{fps}</update_rate>").replace("0.065 0 0.025 0 0.2618 0", "0.065 0 0.025 0 0 0").replace("<horizontal_fov>2.094</horizontal_fov>", "<horizontal_fov>1.668</horizontal_fov>") + t[i1:]
    t = t.replace('<model name="droneforge_3in">', '<model name="droneforge_3in_house">')
    open(p, "w").write(t)
    cfg = os.path.join(dst, "model.config"); c = open(cfg).read().replace("<name>droneforge_3in</name>", "<name>droneforge_3in_house</name>"); open(cfg, "w").write(c)
    model = "droneforge_3in_house"
src = open(os.path.join(HERE, "third_party/small_house_src/worlds/small_house.world")).read()
src = src.replace("<world name='default'>", "<world name='droneforge_house'>", 1)
src = re.sub(r"<max_step_size>0\.005</max_step_size>", "<max_step_size>0.0041666666667</max_step_size>", src, 1)      # 1/240 s: exactly 8 steps per 30 fps camera frame (0.004 s gave 36 ms = 27.8 fps; 1/300 s could not keep real time)
inc = f'''
    <!-- DroneForge 3-inch drone (382.5 g), starts in the living room -->
    <include>
      <uri>model://{model}</uri>
      <name>droneforge_3in</name>
      <pose>{x} {y} 0.05 0 0 {yaw}</pose>
    </include>
'''
i = src.rindex("</world>"); src = src[:i] + inc + src[i:]
hdr = ("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- DroneForge indoor test world: the AWS RoboMaker Small House (https://github.com/IntelligentRoboticsLabs/aws-robomaker-small-house-world, ros2 branch, "
       "MIT No Attribution) with the DroneForge 3-inch drone added. Generated by gazebo/tools/make_house_world.py. Resource path: gazebo/third_party/small_house_src/models. -->")
src = src.replace('<?xml version="1.0" encoding="utf-8"?>', hdr, 1)
open(os.path.join(HERE, "worlds/droneforge_house.sdf"), "w").write(src); print("worlds/droneforge_house.sdf written")
